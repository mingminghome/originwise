// Regenerates functions/_lib/search/dictionary.ts from SCOWL (npm wordlist-english, a devDependency).
// Deterministic: fixed lists and levels, lowercase common-word entries only (no proper nouns / capitalised
// entries), sorted, de-duplicated. Run: npm run build:dictionary
import { createRequire } from 'node:module';
import { writeFileSync } from 'node:fs';

const require = createRequire(import.meta.url);
const VERSION = require('wordlist-english/package.json').version;
const LISTS = ['english', 'american', 'british'];
const LEVELS = [10, 20, 35, 40, 50, 55, 60];
const words = new Set();
for (const list of LISTS)
  for (const level of LEVELS)
    for (const w of require(`wordlist-english/${list}-words-${level}.json`)) if (/^[a-z]{3,}$/.test(w)) words.add(w);
const sorted = [...words].sort();
const out = `/* eslint-disable */
// GENERATED by scripts/build-dictionary.mjs; do not edit by hand.
// Source: SCOWL (Spell Checker Oriented Word Lists) via npm wordlist-english@${VERSION} (package licence MIT).
// Lists: ${LISTS.join(' + ')} (en, en-US, en-GB); SCOWL size levels ${LEVELS.join(', ')}; lowercase common-word
// entries of 3+ letters only (no proper nouns, no capitalised entries). ${sorted.length} words.
// Licence: SCOWL word lists Copyright 2000-2016 Kevin Atkinson, permissive (see dictionary.LICENSE.txt).
// Server side only (functions/_lib); never imported by the client bundle.
export const ENGLISH_WORDS: ReadonlySet<string> = new Set(
  '${sorted.join(' ')}'.split(' ')
);
`;
writeFileSync(new URL('../functions/_lib/search/dictionary.ts', import.meta.url), out);
console.log(`dictionary.ts: ${sorted.length} words (wordlist-english@${VERSION}, levels ${LEVELS.join(',')})`);
